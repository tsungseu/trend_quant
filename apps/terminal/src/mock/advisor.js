// 根据用户输入匹配回复
export function matchReply(text) {
  const t = text.toLowerCase()
  if (/持仓|诊断|健康|组合/.test(t)) return replyDB.diagnose
  if (/大盘|市场|走势|行情|指数/.test(t)) return replyDB.market
  if (/仓位|配置|调整|再平衡/.test(t)) return replyDB.position
  if (/策略|推荐|建议.*买|怎么投/.test(t)) return replyDB.strategy
  if (/风险|回撤|波动|敞口|压力/.test(t)) return replyDB.risk
  if (/夏普|sharpe|指标.*解释|什么意思/.test(t)) return replyDB.explain
  return replyDB.default
}
